import type { Agreement } from '../types'
import { buildClauses } from '../lib/agreementText'
import { fmtDate } from '../lib/calc'

export default function AgreementDoc({ a }: { a: Agreement }) {
  const clauses = buildClauses(a)
  const sig = (s: Agreement['signatures']['provider'], who: string, biz: string) => (
    <div className="sig">
      <div className="s">{s ? s.name : ''}</div>
      <div>
        <b>{who || '—'}</b>
        {biz ? `, ${biz}` : ''}
      </div>
      <div className="muted">{s ? `Signed ${fmtDate(s.signedAt)}` : 'Not yet signed'}</div>
    </div>
  )
  return (
    <article className="doc">
      <h2>Profit Share Agreement</h2>
      <div className="sub">{a.title || 'Untitled'}</div>
      <ol>
        {clauses.map((c) => (
          <li key={c.heading}>
            <h4>{c.heading}</h4>
            <p>{c.body}</p>
          </li>
        ))}
      </ol>
      <div className="sigs">
        {sig(a.signatures.provider, a.provider.name, a.provider.business)}
        {sig(a.signatures.partner, a.partner.name, a.partner.business)}
      </div>
      <div className="disclaimer">
        Template generated by Stakeforward. It's a starting point, not legal advice. Have a lawyer licensed in {a.governingState || 'your state'} review it before you rely on it,
        especially the definition of profit and any tax treatment.
      </div>
    </article>
  )
}
